//! Child context is prepared entirely in the parent. The child executable is
//! assembly even in debug builds: no compiler-generated panic/UB-check calls.
//! All pointers refer to parent-prepared private COW memory. Syscall errors exit.
//! Source and generated assembly require independent review on BOTH ABIs.
use super::super::lifecycle_layout::Raw;
use crate::x11_credentials::MAX_AUTH_BYTES;

#[repr(C)]
pub(super) struct Child {
    pub deadline: super::deadline::Absolute,
    pub endpoint: i32,
    pub parent_pid: i32,
    pub parent_tid: i32,
    pub path: *const u8,
    pub bytes: *mut u8, // MAX_AUTH_BYTES + 1, allocated before spawn
    pub stat: libc::stat,
    pub frame: [u8; 12],
    /// Test-only checkpoint protocol, precomputed in the parent (0 in release).
    pub checkpoints: bool,
    pub lifecycle: *mut Raw, // test-only observations; null and assembled out in production
}

#[cfg(target_arch = "x86_64")]
core::arch::global_asm!(include_str!("leaf_x86_64.S"),
    clock_gettime = const libc::SYS_clock_gettime,
    monotonic = const libc::CLOCK_MONOTONIC,
    deadline_seconds = const std::mem::offset_of!(Child, deadline) + std::mem::offset_of!(super::deadline::Absolute, seconds),
    deadline_nanos = const std::mem::offset_of!(Child, deadline) + std::mem::offset_of!(super::deadline::Absolute, nanos),
    creator_admission = const crate::x11_credentials::launcher::creator::ADMISSION,
    lifecycle_enabled = const cfg!(test) as u8,
    lifecycle_ptr = const std::mem::offset_of!(Child, lifecycle),
    probe_hold = const std::mem::offset_of!(Raw, child_hold),
    probe_reached = const std::mem::offset_of!(Raw, child_reached),
    probe_release = const std::mem::offset_of!(Raw, child_release),
    probe_entered = const std::mem::offset_of!(Raw, path_entered),
    probe_returned = const std::mem::offset_of!(Raw, path_returned),
    futex = const libc::SYS_futex,
    prctl = const libc::SYS_prctl,
    pdeathsig = const libc::PR_SET_PDEATHSIG,
    sigkill = const libc::SIGKILL,
    getppid = const libc::SYS_getppid,
    tgkill = const libc::SYS_tgkill,
    dup3 = const libc::SYS_dup3,
    cloexec = const libc::O_CLOEXEC,
    close_range = const libc::SYS_close_range,
    openat = const libc::SYS_openat,
    at_fdcwd = const libc::AT_FDCWD,
    open_flags = const libc::O_RDONLY | libc::O_CLOEXEC | libc::O_NONBLOCK,
    enoent = const libc::ENOENT,
    fstat = const libc::SYS_fstat,
    read = const libc::SYS_read,
    eintr = const libc::EINTR,
    close = const libc::SYS_close,
    sendto = const libc::SYS_sendto,
    nosignal = const libc::MSG_NOSIGNAL,
    exit_group = const libc::SYS_exit_group,
    ifmt = const libc::S_IFMT,
    ifreg = const libc::S_IFREG,
    max_bytes = const MAX_AUTH_BYTES,
    parent_pid = const std::mem::offset_of!(Child, parent_pid),
    parent_tid = const std::mem::offset_of!(Child, parent_tid),
    endpoint = const std::mem::offset_of!(Child, endpoint),
    checkpoints = const std::mem::offset_of!(Child, checkpoints),
    path = const std::mem::offset_of!(Child, path),
    bytes = const std::mem::offset_of!(Child, bytes),
    stat = const std::mem::offset_of!(Child, stat),
    stat_mode = const std::mem::offset_of!(Child, stat) + std::mem::offset_of!(libc::stat, st_mode),
    stat_size = const std::mem::offset_of!(Child, stat) + std::mem::offset_of!(libc::stat, st_size),
    frame = const std::mem::offset_of!(Child, frame),
    frame_status = const std::mem::offset_of!(Child, frame) + 5,
    frame_length = const std::mem::offset_of!(Child, frame) + 8,
    buffer_bytes = const MAX_AUTH_BYTES + 1,
);

